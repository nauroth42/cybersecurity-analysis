#!/usr/bin/env python3
"""
2_data_extraction_cleansing.py

Data Extraction and Cleansing Script for SEC 10-K Item 1C
(Cybersecurity Disclosure) Text.

This script reads the raw cybersecurity disclosure data generated by
1_data_aquisition_pydoc.py, performs text normalization and cleansing,
and prepares the resulting dataset for downstream machine learning,
natural language processing (NLP), and text analytics tasks.

Background
----------
The acquisition script retrieves Item 1C (Cybersecurity) sections from
annual SEC 10-K filings and stores them in a raw pipe-delimited file:

    ../data/item1c_<year>_raw.csv

The purpose of this script is to transform the raw filing text into a
cleaner representation suitable for:

* Text classification
* Topic modeling
* Sentiment analysis
* Transformer fine-tuning
* Cybersecurity disclosure research

Input
-----
Pipe-delimited file generated by:

    1_data_aquisition_pydoc.py

Example:

    ../data/item1c_2024_raw.csv

Expected format:

    CIK|Item1C_Text

Output
------
A cleaned dataset containing normalized text.

Typical cleaning operations include:

* Removal of non-ASCII characters
* Removal of excessive whitespace
* Normalization of line breaks
* Removal of control characters
* Lowercasing (optional)
* Removal of unwanted symbols

Dependencies
------------
Python Standard Library:

* csv
* re

Author
------
Markus Nauroth

Version
-------
1.0
"""

import csv
import re
import sys

# ---------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------

YEAR = 2026
INPUT_FILE = f'../data/item1c_{YEAR}_raw.csv'
OUTPUT_FILE = f'../data/item1c_{YEAR}_clean.csv'

# Set CSV field size limit to maximum supported value
csv.field_size_limit(sys.maxsize)

def clean_text(raw_text: str) -> str:
    """
    Clean and normalize raw Item 1C filing text.

    Parameters
    ----------
    raw_text : str
        Raw cybersecurity disclosure text extracted from the
        SEC filing.

    Returns
    -------
    str
        Cleaned and normalized text.

    Notes
    -----
    Processing steps:

    1. Remove non-ASCII characters.
    2. Replace multiple whitespace characters with a single space.
    3. Remove carriage returns and tabs.
    4. Trim leading and trailing whitespace.
    """

    if not raw_text:
        return ""

    # Remove non-ASCII characters
    text = raw_text.encode("ascii", "ignore").decode("ascii")

    # Replace tabs and line breaks with spaces
    text = re.sub(r'\\[nrt]', ' ', text)

    # Replace \xa0 with spaces
    text = re.sub(r'\\xa0', ' ', text)

    # Collapse multiple whitespace characters
    text = re.sub(r'\s+', ' ', text)

    # Remove leading/trailing spaces
    text = text.strip()

    return text[:200000]


def process_file(input_file: str, output_file: str) -> None:
    """
    Copy all fields from the raw dataset and append a cleaned
    version of the Item 1C text.

    Input:
        CIK | Year | FilingDate | ReportingDate | RawText

    Output:
        CIK | Year | FilingDate | ReportingDate | RawText | CleanText
    """

    with open(
        input_file,
        "r",
        encoding="utf-8",
        newline=""
    ) as infile, open(
        output_file,
        "w",
        encoding="utf-8",
        newline=""
    ) as outfile:

        reader = csv.reader(infile, delimiter="|")
        writer = csv.writer(outfile, delimiter="|")

        # header
        writer.writerow([
            "CIK",
            "Year",
            "FilingDate",
            "ReportingDate",
            "CleanText"
        ])

        for row in reader:

            # Skip malformed rows
            if len(row) < 5:
                continue

            cik = row[0]
            year = row[1]
            filing_date = row[2]
            reporting_date = row[3]
            raw_txt = row[4].strip("[]")
            clean_txt = clean_text(raw_txt)

            writer.writerow([
                cik,
                year,
                filing_date,
                reporting_date,
                clean_txt
            ])

            with open(f'../data/item_1c/{cik}_{year}.txt', 'w') as txt_file:
                txt_file.write(clean_txt)


def main() -> None:
    """
    Program entry point.

    Reads the raw Item 1C dataset produced by
    1_data_aquisition_pydoc.py and generates a
    cleaned version suitable for analytics.

    Returns
    -------
    None
    """

    print("Starting Item 1C cleansing process...")

    process_file(
        INPUT_FILE,
        OUTPUT_FILE
    )

    print("Processing complete.")


if __name__ == "__main__":
    main()