def df_to_hf(df):
    """
    Convert a pandas DataFrame into a Hugging Face Dataset object.

    This helper function transforms a pandas DataFrame into the
    format required by the Hugging Face Transformers ecosystem.
    The index is reset to ensure that no unnecessary index column
    is carried into the resulting dataset.

    Parameters
    ----------
    df : pandas.DataFrame
        Input DataFrame containing document text and label columns.

    Returns
    -------
    datasets.Dataset
        Hugging Face Dataset representation of the input data.

    Notes
    -----
    Hugging Face Datasets provide efficient memory handling,
    dataset mapping, tokenization, caching, and integration with
    transformer training pipelines.

    Examples
    --------
    >>> hf_dataset = df_to_hf(train_df)
    >>> len(hf_dataset)
    1000
    """
    return Dataset.from_pandas(df.reset_index(drop=True))


def format_labels(ex):
    """
    Construct a multi-label target vector for a single document.

    This function collects all classification labels listed in
    LABEL_COLS and stores them in a single list named 'labels'.

    The resulting structure is compatible with Hugging Face's
    Trainer API for multi-label classification tasks.

    Parameters
    ----------
    ex : dict
        Single dataset record containing text and individual
        label columns.

    Returns
    -------
    dict
        Updated example containing a new 'labels' field.

    Notes
    -----
    Multi-label classification differs from single-label
    classification because an individual document may belong
    to multiple categories simultaneously.

    Example
    -------
    Input:

        {
            "Risk": 1,
            "Governance": 0,
            "Strategy": 1
        }

    Output:

        {
            "labels": [1.0, 0.0, 1.0]
        }
    """
    ex["labels"] = [float(ex[c]) for c in LABEL_COLS]
    return ex


def tokenize_fn(ex, tok):
    """
    Tokenize document text for transformer input.

    This function converts raw text into token IDs and attention
    masks that can be processed by transformer architectures.

    Parameters
    ----------
    ex : dict
        Dataset record containing a text field.

    tok : transformers.PreTrainedTokenizer
        Tokenizer corresponding to the transformer checkpoint
        currently being trained.

    Returns
    -------
    dict
        Tokenized representation including:

        * input_ids
        * attention_mask
        * token_type_ids (if supported)

    Notes
    -----
    Documents longer than 512 tokens are truncated because most
    transformer architectures have a maximum sequence length of
    512 tokens.

    Padding is applied so that all training batches have
    consistent dimensions.

    Examples
    --------
    >>> tokenize_fn(record, tokenizer)

    Returns tokenized tensors suitable for training.
    """
    return tok(
        ex["text"],
        max_length=512,
        truncation=True,
        padding="max_length",
    )


def get_torch_columns(ds):
    """
    Determine which columns should be supplied to PyTorch.

    Different transformer architectures expect different
    input structures.

    For example:

    * BERT supports token_type_ids
    * RoBERTa does not use token_type_ids
    * DistilBERT does not use token_type_ids

    This helper function dynamically selects only those
    columns required by the currently loaded model.

    Parameters
    ----------
    ds : datasets.Dataset
        Tokenized Hugging Face dataset.

    Returns
    -------
    list[str]
        List of dataset columns that should be converted
        to PyTorch tensors.

    Notes
    -----
    Excluding unsupported columns prevents runtime shape
    mismatch errors during training.

    Examples
    --------
    >>> get_torch_columns(ds)

    ['input_ids', 'attention_mask', 'labels']

    or

    ['input_ids',
     'attention_mask',
     'token_type_ids',
     'labels']
    """
    keep = ["input_ids", "attention_mask", "labels"]

    if "token_type_ids" in ds.column_names:
        keep.append("token_type_ids")

    return keep


def multi_metrics(pred):
    """
    Compute evaluation metrics for a multi-label classifier.

    This function is called automatically by Hugging Face's
    Trainer during validation and testing.

    Model logits are first converted into probabilities using
    the sigmoid activation function.

    A probability threshold of 0.50 is then applied to generate
    binary predictions for each class.

    Parameters
    ----------
    pred : tuple
        Tuple provided by the Trainer consisting of:

        logits : numpy.ndarray
            Raw model outputs before activation.

        labels : numpy.ndarray
            Ground-truth target labels.

    Returns
    -------
    dict
        Dictionary containing evaluation metrics.

        Typical metrics include:

        * accuracy
        * precision
        * recall
        * f1
        * roc_auc

    Notes
    -----
    Multi-label classification requires sigmoid activation.

    Softmax should NOT be used because:

        * Multiple labels may be true simultaneously.
        * Class probabilities are independent.

    Thresholding Strategy
    ---------------------
    A threshold of 0.50 is applied:

        probability >= 0.50

    resulting in a positive prediction.

    Researchers may experiment with alternative thresholds
    to optimize precision-recall trade-offs.

    Statistical Interpretation
    --------------------------
    Accuracy
        Overall proportion of correct predictions.

    Precision
        Fraction of predicted positive labels that are
        actually positive.

    Recall
        Fraction of actual positive labels that are
        correctly identified.

    F1 Score
        Harmonic mean of precision and recall.

    ROC-AUC
        Measures class separability across all possible
        classification thresholds.

    Examples
    --------
    >>> metrics = multi_metrics(pred)
    >>> metrics["f1"]
    0.84

    References
    ----------
    Powers, D.M.W. (2020).
    Evaluation: From Precision, Recall and F-Measure to
    ROC, Informedness, Markedness and Correlation.
    """
    logits, labs = pred

    probs = torch.sigmoid(
        torch.tensor(logits)
    ).numpy()

    preds = (probs >= 0.5).astype(int)

    labs = labs.astype(int)

    acc = accuracy_score(labs, preds)

    p_micro = precision_score(labs, preds, average="micro", zero_division=0)
    r_micro = recall_score(labs, preds, average="micro", zero_division=0)
    f_micro = f1_score(labs, preds, average="micro", zero_division=0)
    p_macro = precision_score(labs, preds, average="macro", zero_division=0)
    r_macro = recall_score(labs, preds, average="macro", zero_division=0)
    f_macro = f1_score(labs, preds, average="macro", zero_division=0)

    try:
        auc_macro = roc_auc_score(labs, probs, average="macro")
    except ValueError:
        auc_macro = float("nan")

    return {
        "accuracy": acc,
        "precision_micro": p_micro,
        "recall_micro": r_micro,
        "f1_micro": f_micro,
        "precision_macro": p_macro,
        "recall_macro": r_macro,
        "f1_macro": f_macro,
        "auc_macro": auc_macro,
    }


